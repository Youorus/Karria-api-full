# Priorité des logos (ADR-0021) : la dernière annonce vue de chaque
# entreprise, remplie depuis ses offres actives ; idempotente, appliquée
# avant le code qui la lit.


async def upgrade(db: BaseDBAsyncClient) -> str:
    return """
        ALTER TABLE "offers_companies" ADD COLUMN IF NOT EXISTS "last_offer_at" TIMESTAMPTZ;
        COMMENT ON COLUMN offers_companies."last_offer_at" IS 'Dernière annonce vue (à l''heure près) : priorité du logo.';
        CREATE INDEX IF NOT EXISTS "idx_offers_comp_logo_st_00feed" ON "offers_companies" ("logo_status", "last_offer_at");
        UPDATE "offers_companies" AS c SET "last_offer_at" = s.latest
          FROM (SELECT company_id, max(first_seen_at) AS latest FROM offers_offers
                 WHERE is_active AND company_id IS NOT NULL GROUP BY company_id) AS s
         WHERE c.id = s.company_id AND c."last_offer_at" IS NULL;"""


async def downgrade(db: BaseDBAsyncClient) -> str:
    return """
        DROP INDEX IF EXISTS "idx_offers_comp_logo_st_00feed";
        ALTER TABLE "offers_companies" DROP COLUMN "last_offer_at";"""


