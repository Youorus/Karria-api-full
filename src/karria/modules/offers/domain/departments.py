def neighbours_of(codes: Sequence[str]) -> list[str]:
    """Les départements limitrophes de ceux-là, hors ceux-là, triés."""
    wanted = {c.upper() for c in codes}
    found: set[str] = set()
    for code, adjacent in _ADJACENT.items():
        if code in wanted:
            found.update(adjacent)
        if wanted & set(adjacent):
            found.add(code)
    return sorted(found - wanted)
